function applyXPartPreviewImages(items) {
  const previewsByBeyId = new Map();
  for (const entry of xPartPreviewMappings) {
    if (!previewsByBeyId.has(entry.beyId)) previewsByBeyId.set(entry.beyId, {});
    previewsByBeyId.get(entry.beyId)[entry.partId] = entry.image;
  }
  for (const item of items) {
    const previews = previewsByBeyId.get(item.id);
    if (previews) item.partPreviewImages = previews;
  }
}

